def binary_search(sorted_list, item_to_find):
    """
    Выполняет бинарный поиск элемента в отсортированном списке.

    :param sorted_list: Отсортированный список, в котором ищем (наш склад).
    :param item_to_find: Элемент, который нужно найти (буква Робота).
    :return: Индекс элемента, если он найден, иначе None.
    """
    # Начальная точка поиска — самая первая коробка (индекс 0)
    low = 0
    # Верхняя граница поиска — самая последняя коробка.
    # Помни, что нумерация в Python начинается с 0!
    high = len(sorted_list) - 1

    # Наш главный цикл поиска. Он продолжается, пока
    # нижняя граница не "перепрыгнет" через верхнюю.
    while low <= high:
        
        # Находим и проверяем коробку точно посередине
        mid = (low + high) // 2
        guess = sorted_list[mid]

        # 1. Победа! Мы нашли то, что искали.
        if guess == item_to_find:
            return mid

        # 2. Наша проба оказалась "дальше" нужной буквы.
        # Значит, нужно сдвинуть ВЕРХНЮЮ границу поиска.
        if guess > item_to_find:
            high = mid - 1
        
        # 3. Наша проба оказалась "раньше" нужной буквы.
        # Значит, нужно сдвинуть НИЖНЮЮ границу.
        else:
            low = mid + 1

    # Если мы вышли из цикла, значит, перебрали все варианты,
    # а Робота так и не нашли.
    return None

# --- Проверка твоего кода ---

# Наш отсортированный "склад" с коробками-буквами
my_alphabet = ['А', 'Б', 'В', 'Г', 'Д', 'Е', 'Ж', 'З', 'И', 'К', 'Л', 'М', 'Н', 'О', 'П', 'Р', 'С', 'Т', 'У', 'Ф', 'Х', 'Ц', 'Ч', 'Ш', 'Щ', 'Э', 'Ю', 'Я']
robot_letter = 'Р' # Буква, на которой спрятан Робот

# Вызываем твою функцию
found_index = binary_search(my_alphabet, robot_letter)

# Проверяем результат
if found_index is not None:
    print(f"Отлично! Робот найден в коробке с индексом {found_index} (это буква '{my_alphabet[found_index]}')")
else:
    print("Хм, робот не найден. Проверь код в своей программе и попробуй еще раз!")